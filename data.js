  const amountEth = (Math.random() * 0.45 + 0.025).toFixed(3);
  const ethRate = 2456.79 + (Math.random() * 4 - 2);
  const amountUsd = (amountEth * ethRate).toFixed(2);
  const fullWallet = WHALE_WALLETS[Math.floor(Math.random() * WHALE_WALLETS.length)];
  const shortWallet = fullWallet.substring(0, 6) + "..." + fullWallet.substring(fullWallet.length - 4);
